import type { RenderContext } from '../../types/render.js';

/*** Render optional contributor markers without displaying an empty heading. */
export function renderCollaborators(
  context: RenderContext,
): Pick<RenderContext['result'], 'collaboratorsWorkflowYaml' | 'readme'> {
  if (context.model.collaborators === null) {
    return { collaboratorsWorkflowYaml: null, readme: context.result.readme };
  }
  return {
    collaboratorsWorkflowYaml: renderCollaboratorsWorkflowYaml(),
    readme: renderCollaboratorsReadme(context.result.readme),
  };
}

const collaboratorsMarkers = [
  '<!-- readme: contributors -start -->',
  '<!-- readme: contributors -end -->',
].join('\n');

/*** Keep invisible markers so the GitHub workflow can insert avatars when present. */
function renderCollaboratorsReadme(readme: string): string {
  return readme.trimEnd() + '\n\n' + collaboratorsMarkers + '\n';
}

/*** Generate the source-owned contributors workflow without a broken table action. */
function renderCollaboratorsWorkflowYaml(): string {
  return [
    '# Generated by Paradox. Do not edit manually.',
    'name: Update contributors',
    '',
    'on:',
    '  schedule:',
    "    - cron: '17 3 * * 1'",
    '  workflow_dispatch:',
    '',
    'concurrency:',
    '  group: paradox-contributors-${{ github.repository }}',
    '  cancel-in-progress: false',
    '',
    'permissions:',
    '  contents: write',
    '  pull-requests: write',
    '',
    'jobs:',
    '  contributors:',
    '    name: Update contributors',
    '    runs-on: ubuntu-latest',
    '    steps:',
    '      - name: Checkout repository',
    '        uses: actions/checkout@v4',
    '      - name: Render contributor avatars',
    '        env:',
    '          GH_TOKEN: ${{ secrets.GITHUB_TOKEN }}',
    '        run: |',
    "          node --input-type=module <<'NODE'",
    ...contributorScript.trimEnd().split('\n').map((line) => '          ' + line),
    '          NODE',
    '      - name: Propose contributor update',
    '        env:',
    '          GH_TOKEN: ${{ secrets.GITHUB_TOKEN }}',
    '        run: |',
    '          if git diff --quiet -- README.md; then exit 0; fi',
    '          if gh pr list --state open --limit 100 --json title --jq ".[] | .title" | grep -Fqx "docs(contributors): refresh avatar list"; then',
    '            echo "Contributor update PR already open; avoiding duplicates."',
    '            exit 0',
    '          fi',
    '          git config user.name "github-actions[bot]"',
    '          git config user.email "41898282+github-actions[bot]@users.noreply.github.com"',
    '          branch="automation/paradox-contributors-${GITHUB_RUN_ID}"',
    '          git switch -c "$branch"',
    '          git add -- README.md',
    '          git commit -m "docs(contributors): refresh avatar list"',
    '          git push -u origin HEAD',
    '          gh pr create --base main --head "$branch" --title "docs(contributors): refresh avatar list" --body "Generated contributor-avatar refresh; no hand-edited documentation." --assignee artiphishle',
    '',
  ].join('\n');
}

const contributorScript = [
  "import { readFileSync, writeFileSync } from 'node:fs';",
  "",
  "const [owner, repo] = (process.env.GITHUB_REPOSITORY || '').split('/');",
  "const token = process.env.GH_TOKEN;",
  "if (!owner || !repo || !token) throw new Error('Contributors require repository identity and token.');",
  "",
  "const contributors = [];",
  "for (let page = 1; page <= 10; page += 1) {",
  "  const url = 'https://api.github.com/repos/' + encodeURIComponent(owner) + '/' +",
  "    encodeURIComponent(repo) + '/contributors?per_page=100&page=' + page;",
  "  const response = await fetch(url, {",
  "    headers: { Accept: 'application/vnd.github+json', Authorization: 'Bearer ' + token },",
  "  });",
  "  if (response.status === 204) break;",
  "  if (!response.ok) throw new Error('Contributors API returned HTTP ' + response.status);",
  "  const batch = await response.json();",
  "  if (!Array.isArray(batch)) throw new Error('Unexpected contributors API result.');",
  "  for (const item of batch) {",
  "    if (item?.type !== 'User' || typeof item.login !== 'string') continue;",
  "    if (!/^[A-Za-z0-9](?:[A-Za-z0-9-]{0,38})$/.test(item.login)) continue;",
  "    if (!Number.isSafeInteger(item.id) || item.id <= 0) continue;",
  "    contributors.push({ login: item.login, id: item.id });",
  "  }",
  "  if (batch.length < 100) break;",
  "}",
  "",
  "const source = readFileSync('README.md', 'utf8');",
  "const start = '<!-- readme: contributors -start -->';",
  "const end = '<!-- readme: contributors -end -->';",
  "const left = source.indexOf(start);",
  "const right = source.indexOf(end);",
  "if (left < 0 || right < left) {",
  "  console.log('No enabled Paradox contributor markers; nothing to update.');",
  "  process.exit(0);",
  "}",
  "",
  "const avatars = contributors.map((user) =>",
  "  '<a href=\"https://github.com/' + user.login + '\">' +",
  "  '<img src=\"https://avatars.githubusercontent.com/u/' + user.id +",
  "  '?v=4&amp;s=72\" width=\"72\" height=\"72\" alt=\"' + user.login + '\" /></a>'",
  ").join(' ');",
  "const section = avatars",
  "  ? '\\n<!-- Generated by Paradox contributor avatars -->\\n\\n## Contributors\\n\\n' + avatars + '\\n'",
  "  : '\\n';",
  "const updated = source.slice(0, left + start.length) + section + source.slice(right);",
  "if (updated !== source) writeFileSync('README.md', updated, 'utf8');",
].join('\n');
