import type { RenderContext } from '../types.js';

export function renderCollaborators(
  context: RenderContext,
): Pick<RenderContext['result'], 'collaboratorsWorkflowYaml' | 'readme'> {
  if (context.model.collaborators === null) {
    return {
      collaboratorsWorkflowYaml: null,
      readme: context.result.readme,
    };
  }

  return {
    collaboratorsWorkflowYaml: renderCollaboratorsWorkflowYaml(),
    readme: renderCollaboratorsReadme(context.result.readme),
  };
}

// Upgrade both values together only after verifying the Marketplace release and immutable tag SHA.
const actionCommit = '83ea0b4f1ac928fbfe88b9e8460a932a528eb79f';
const actionVersion = 'v2.3.11';
const collaboratorsMarkers = [
  '<!-- readme: collaborators -start -->',
  '<!-- readme: collaborators -end -->',
].join('\n');

function renderCollaboratorsReadme(readme: string): string {
  return `${readme.trimEnd()}\n\n## Collaborators\n\n${collaboratorsMarkers}\n`;
}

function renderCollaboratorsWorkflowYaml(): string {
  return [
    '# Generated by Paradox. Do not edit manually.',
    'name: Update collaborators',
    '',
    'on:',
    '  schedule:',
    "    - cron: '17 3 * * 1'",
    '  workflow_dispatch:',
    '',
    'permissions:',
    '  contents: write',
    '  pull-requests: write',
    '',
    'jobs:',
    '  collaborators:',
    '    name: Update collaborators',
    '    runs-on: ubuntu-latest',
    '    steps:',
    '      - name: Update collaborators',
    `        uses: akhilmhdh/contributors-readme-action@${actionCommit} # ${actionVersion}`,
    '        with:',
    '          readme_path: README.md',
    '          collaborators: direct',
    '        env:',
    '          GITHUB_TOKEN: ${{ secrets.GITHUB_TOKEN }}',
    '',
  ].join('\n');
}
