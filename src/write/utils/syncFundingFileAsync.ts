import { mkdir, readFile, unlink, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';

export async function syncFundingFileAsync(
  packageRoot: string,
  fundingYaml: string | null,
): Promise<void> {
  const fundingPath = join(packageRoot, '.github', 'FUNDING.yml');
  const existing = await readFundingFileAsync(fundingPath);

  if (fundingYaml === null) {
    if (existing !== null && isParadoxOwnedFunding(existing)) await unlink(fundingPath);
    return;
  }

  if (existing !== null && !isParadoxOwnedFunding(existing)) {
    throw new Error('Refusing to overwrite existing non-Paradox .github/FUNDING.yml.');
  }

  await mkdir(dirname(fundingPath), { recursive: true });
  await writeFile(fundingPath, fundingYaml);
}

const generatedFundingMarker = '# Generated by Paradox. Do not edit manually.';

function isParadoxOwnedFunding(content: string): boolean {
  return content.startsWith(`${generatedFundingMarker}\n`);
}

async function readFundingFileAsync(path: string): Promise<string | null> {
  try {
    return await readFile(path, 'utf-8');
  } catch (error: unknown) {
    if (error instanceof Error && 'code' in error && error.code === 'ENOENT') return null;
    throw error;
  }
}
