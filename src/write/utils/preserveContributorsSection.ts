const startMarker = '<!-- readme: contributors -start -->';
const endMarker = '<!-- readme: contributors -end -->';
const snapshotMarker = '<!-- Generated by Paradox contributor avatars -->';

/*** Retain a verified generated avatar section across release-time README regeneration. */
export function preserveContributorsSection(generated: string, existing: string): string {
  const saved = betweenMarkers(existing);
  const generatedSection = betweenMarkers(generated);
  if (saved === null || generatedSection === null) return generated;
  const content = saved.trim();
  if (
    !content.startsWith(snapshotMarker) ||
    !content.includes('## Contributors') ||
    !content.includes('<img src="https://avatars.githubusercontent.com/u/') ||
    content.includes('<table')
  ) {
    return generated;
  }
  const startIndex = generated.indexOf(startMarker) + startMarker.length;
  const endIndex = generated.indexOf(endMarker, startIndex);
  return generated.slice(0, startIndex) + '\n' + content + '\n' + generated.slice(endIndex);
}

/*** Extract exactly one complete contributor marker section from a README. */
function betweenMarkers(readme: string): string | null {
  const startIndex = readme.indexOf(startMarker);
  if (startIndex < 0 || readme.lastIndexOf(startMarker) !== startIndex) return null;
  const contentStart = startIndex + startMarker.length;
  const endIndex = readme.indexOf(endMarker, contentStart);
  if (endIndex < 0 || readme.lastIndexOf(endMarker) !== endIndex) return null;
  return readme.slice(contentStart, endIndex);
}
