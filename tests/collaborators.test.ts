import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

import { expect, test } from 'bun:test';

import { analyze } from '../src/analyze/analyze.js';
import { readGitHubContributorsAsync } from '../src/features/contributors/adapters/readGitHubContributorsAsync.js';
import { buildModel } from '../src/model/buildModel.js';
import { render } from '../src/render/render.js';
import type { ParadoxConfig } from '../src/types/config.js';
import type { Contributor } from '../src/types/contributors.js';
import { write } from '../src/write/write.js';

const contributors = [{ login: 'example-user', id: 123 }] satisfies Contributor[];
const generatedWorkflow =
  '# Generated by Paradox. Do not edit manually.\nname: Update contributors\n';

test('defaults to enabled but renders no empty Contributors heading', async () => {
  const root = await createFixtureAsync();
  try {
    const { analysis, model, result } = await renderFixtureAsync(root);
    expect(analysis.collaborators).toBeTrue();
    expect(model.collaborators).toBeTrue();
    expect(result.readme).not.toContain('## Contributors');
    expect(result.readme).not.toContain('readme: contributors');
  } finally {
    await rm(root, { force: true, recursive: true });
  }
});

test('renders clickable avatars before Donation without a table or workflow', async () => {
  const root = await createFixtureAsync();
  try {
    const { result } = await renderFixtureAsync(root, { donation: true, contributors });
    expect(result.readme).toContain('## Contributors');
    expect(result.readme).toContain(
      '<a href="https://github.com/example-user"><img src="https://avatars.githubusercontent.com/u/123?s=64" width="40" height="40" alt="example-user" /></a>',
    );
    expect(result.readme).not.toContain('<table>');
    expect(result.readme.indexOf('## Donation')).toBeGreaterThan(
      result.readme.indexOf('## Contributors'),
    );
    expect(result.indexHtml).not.toContain('<h2>Contributors</h2>');
  } finally {
    await rm(root, { force: true, recursive: true });
  }
});

test('explicit opt-out suppresses even supplied contributors', async () => {
  const root = await createFixtureAsync();
  try {
    const { analysis, result } = await renderFixtureAsync(root, {
      collaborators: false,
      contributors,
    });
    expect(analysis.collaborators).toBeNull();
    expect(result.readme).not.toContain('## Contributors');
    expect(result.readme).not.toContain('example-user');
  } finally {
    await rm(root, { force: true, recursive: true });
  }
});

test('write mode removes only the obsolete Paradox workflow and remains idempotent', async () => {
  const root = await createFixtureAsync();
  const workflowPath = join(root, '.github', 'workflows', 'collaborators.yml');
  const runtime = { packageRoot: root, outputRoot: join(root, 'paradox') };
  try {
    await mkdir(join(root, '.github', 'workflows'), { recursive: true });
    await writeFile(workflowPath, generatedWorkflow.replaceAll('\n', '\r\n'));
    const { result, config } = await renderFixtureAsync(root, { contributors });
    await write(result, config, runtime);
    expect(await readFile(workflowPath, 'utf8').catch(() => null)).toBeNull();
    const firstReadme = await readFile(join(root, 'README.md'), 'utf8');
    expect(firstReadme).toContain('example-user');
    await write(result, config, runtime);
    expect(await readFile(join(root, 'README.md'), 'utf8')).toBe(firstReadme);
    expect(await readFile(workflowPath, 'utf8').catch(() => null)).toBeNull();

    await writeFile(workflowPath, 'name: User workflow\n');
    await write(result, config, runtime);
    expect(await readFile(workflowPath, 'utf8')).toBe('name: User workflow\n');
  } finally {
    await rm(root, { force: true, recursive: true });
  }
});

test('safe mode does not modify the README or the old workflow', async () => {
  const root = await createFixtureAsync();
  const workflowPath = join(root, '.github', 'workflows', 'collaborators.yml');
  try {
    await mkdir(join(root, '.github', 'workflows'), { recursive: true });
    await writeFile(workflowPath, generatedWorkflow);
    await writeFile(join(root, 'README.md'), '# Original README\n');
    const { result, config } = await renderFixtureAsync(root, { mode: 'safe', contributors });
    await write(result, config, { packageRoot: root, outputRoot: join(root, 'paradox') });
    expect(await readFile(workflowPath, 'utf8')).toBe(generatedWorkflow);
    expect(await readFile(join(root, 'README.md'), 'utf8')).toBe('# Original README\n');
  } finally {
    await rm(root, { force: true, recursive: true });
  }
});

test('reads paginated human contributors and never follows redirects with credentials', async () => {
  const root = await createFixtureAsync();
  try {
    await writeFile(
      join(root, 'package.json'),
      JSON.stringify({
        repository: { url: 'git+https://github.com/example/project.git' },
      }),
    );
    const calls: string[] = [];
    const human = { type: 'User', login: 'example-user', id: 123 };
    const records = [human, ...Array.from({ length: 99 }, () => ({ type: 'Bot' }))];
    const result = await readGitHubContributorsAsync(root, {
      token: 'fixture-token',
      fetchPage: (url, init) => {
        calls.push(url);
        expect(init.redirect).toBe('error');
        expect(new Headers(init.headers).get('Authorization')).toBe('Bearer fixture-token');
        return Promise.resolve(Response.json(url.endsWith('page=1') ? records : [human]));
      },
    });
    expect(result).toEqual(contributors);
    expect(calls).toEqual([
      'https://api.github.com/repos/example/project/contributors?per_page=100&page=1',
      'https://api.github.com/repos/example/project/contributors?per_page=100&page=2',
    ]);
  } finally {
    await rm(root, { force: true, recursive: true });
  }
});

test('fails closed on a GitHub error and skips repositories without GitHub metadata', async () => {
  const root = await createFixtureAsync();
  try {
    const fetchPage = () => Promise.resolve(new Response('provider error', { status: 403 }));
    expect(await readGitHubContributorsAsync(root, { fetchPage })).toEqual([]);
    await writeFile(
      join(root, 'package.json'),
      JSON.stringify({
        repository: 'https://github.com/example/project',
      }),
    );
    expect(readGitHubContributorsAsync(root, { fetchPage })).rejects.toThrow('HTTP 403');
  } finally {
    await rm(root, { force: true, recursive: true });
  }
});

interface FixtureOptions {
  collaborators?: boolean;
  contributors?: readonly Contributor[];
  donation?: true;
  mode?: 'safe' | 'write';
}

function createConfig(options: FixtureOptions = {}): ParadoxConfig {
  return {
    mode: options.mode ?? 'write',
    ...(options.collaborators === undefined ? {} : { collaborators: options.collaborators }),
    ...(options.donation === true ? { donation: { account: 'ankhorage' } } : {}),
    package: { entrypoints: ['src/index.ts'] },
    output: { dir: 'paradox' },
  };
}

async function createFixtureAsync(): Promise<string> {
  const root = join(import.meta.dir, '.tmp', `collaborators-${Date.now()}-${Math.random()}`);
  await mkdir(join(root, 'src'), { recursive: true });
  await writeFile(
    join(root, 'package.json'),
    JSON.stringify({
      name: '@fixture/collaborators',
      version: '1.0.0',
      description: 'Collaborators fixture.',
      license: 'MIT',
    }),
  );
  await writeFile(
    join(root, 'tsconfig.json'),
    JSON.stringify({
      compilerOptions: {
        target: 'ES2022',
        module: 'ESNext',
        moduleResolution: 'Bundler',
        strict: true,
        skipLibCheck: true,
      },
      include: ['src'],
    }),
  );
  await writeFile(join(root, 'src/index.ts'), 'export const value = 1;\n');
  return root;
}

async function renderFixtureAsync(root: string, options: FixtureOptions = {}) {
  const config = createConfig(options);
  const analysis = await analyze(config, { packageRoot: root });
  const model = buildModel(analysis);
  const result = render(model, { outputDir: 'paradox', contributors: options.contributors });
  return { analysis, config, model, result };
}
